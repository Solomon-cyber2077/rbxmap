"""MAP.md and DESIGN.md (+ remotes table) generation."""
from __future__ import annotations

import shutil
import sys
from pathlib import Path

from .project import posix
from .safety import safe_write

MAP_START, MAP_END = "<!-- rbxmap:start -->", "<!-- rbxmap:end -->"
REM_START, REM_END = "<!-- rbxmap:remotes -->", "<!-- rbxmap:remotes:end -->"


def replace_between(text: str, start: str, end: str, body: str) -> str:
    block = f"{start}\n{body.rstrip()}\n{end}"
    a, b = text.find(start), text.find(end)
    if a >= 0 and b > a:
        return text[:a] + block + text[b + len(end):]
    return (text.rstrip() + "\n\n" if text.strip() else "") + block + "\n"


def _read(p: Path) -> str:
    try:
        return p.read_text(encoding="utf-8-sig")
    except OSError:
        return ""


def write_map(app) -> Path:
    rows = app.idx.all_scripts()
    lines = [f"_{len(rows)} scripts. `~` = auto-generated description (add a header comment or "
             f".rbxmap/descriptions.json to replace it). Regenerated by rbxmap; edit outside the markers._", ""]
    for r in rows:
        d = ("~ " if r["desc_auto"] else "") + " ".join((r["descr"] or "").split())
        lines.append(f"- {r['rbx_path']} ({r['class']}) — `{r['fs_path']}` — {d}")
    ni = app.idx.project.not_indexed
    if ni:
        lines += ["", "Not indexed (Studio-only or properties-only):"]
        lines += [f"- {n}" for n in ni]
    path = app.root / "MAP.md"
    text = _read(path) or "# Script map\n\nYour own notes can go above or below the generated block.\n"
    return safe_write(app.root, "MAP.md", replace_between(text, MAP_START, MAP_END, "\n".join(lines)))


DESIGN_TEMPLATE = """# Game design

Planner-owned. Keep it short. Builders read this instead of opening scripts.

## Core loop
- (what the player does every 1-5 minutes)

## Systems
- (one line per system: name, purpose, main script path from MAP.md)

## Data model
- (what is saved per player, DataStore keys, leaderstats)

## Remote events
Auto-generated by `rbxmap remotes`; do not edit between the markers.
{start}
(run `rbxmap remotes`)
{end}

## Naming conventions
- (e.g. RemoteEvents are PascalCase verbs: BuyItem, EquipTool)

## Current priorities
1. (next thing to build)
"""


def ensure_design(root: Path) -> str:
    if (root / "DESIGN.md").exists():
        return "kept existing DESIGN.md"
    safe_write(root, "DESIGN.md", DESIGN_TEMPLATE.format(start=REM_START, end=REM_END))
    return "created DESIGN.md"


def remotes_table(app) -> tuple[str, list]:
    db = app.idx.db
    rows = db.execute("SELECT r.name, r.kind, r.line, s.fs_path FROM remotes r JOIN scripts s ON s.id=r.script_id"
                      " ORDER BY lower(r.name), s.fs_path, r.line").fetchall()
    by = {}
    for r in rows:
        by.setdefault(r["name"], {}).setdefault(r["kind"], []).append(f"`{r['fs_path']}:{r['line']}`")
    for path, cls, pfile in app.idx.project.remote_defs:
        by.setdefault(path.split(" > ")[-1], {}).setdefault("define", []).append(f"{cls} in `{pfile}` ({path})")
    fire = ("fire_server", "fire_client", "invoke_server", "invoke_client")
    handle = ("on_server_event", "on_client_event", "on_server_invoke", "on_client_invoke")
    out = ["| Remote | Fired by | Handled by | Defined |", "|---|---|---|---|"]
    pairs = []
    for name in sorted(by, key=str.lower):
        k = by[name]
        f = [f"{x} ({kind})" for kind in fire for x in k.get(kind, [])]
        h = [f"{x} ({kind})" for kind in handle for x in k.get(kind, [])]
        out.append(f"| {name} | {'<br>'.join(f) or '—'} | {'<br>'.join(h) or '—'} | {'<br>'.join(k.get('define', [])) or '—'} |")
        pairs.append({"name": name, "fired_by": f, "handled_by": h, "defined": k.get("define", [])})
    if not pairs:
        out.append("| (none found) | Remotes created only in Studio or via custom wrappers are invisible; "
                   "set remote_wrappers in .rbxmap/config.json | | |")
    return "\n".join(out), pairs


def write_remotes(app) -> dict:
    ensure_design(app.root)
    table, pairs = remotes_table(app)
    text = _read(app.root / "DESIGN.md")
    safe_write(app.root, "DESIGN.md", replace_between(text, REM_START, REM_END, table))
    return {"remotes": len(pairs), "written": "DESIGN.md", "pairs": pairs}


def exe_hint() -> str:
    found = shutil.which("rbxmap")
    if found:
        return "rbxmap"
    cand = Path(sys.executable).parent / ("rbxmap.exe" if sys.platform == "win32" else "rbxmap")
    return posix(cand) if cand.exists() else "rbxmap"

